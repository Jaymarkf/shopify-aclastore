const fs = require('node:fs');
const path = require('node:path');
const directory = path.resolve('product-import/product-family');
const state = JSON.parse(fs.readFileSync(path.join(directory, 'admin-setup-result.json')));
if (!state.prepared || state.products.length !== 40) throw new Error('Prepare and verify the 40-product group before publication.');
const definitions = ['$publicationId: ID!', ...state.products.map((_, index) => '$id' + index + ': ID!')];
const fields = state.products.map((_, index) => '  item' + index + ': publishablePublish(id: $id' + index + ', input: [{ publicationId: $publicationId }]) { userErrors { field message } }');
const query = 'mutation PublishFamilyItems(' + definitions.join(', ') + ') {\n' + fields.join('\n') + '\n}\n';
fs.writeFileSync(path.join(__dirname, 'publish-family-items.graphql'), query);
const variables = { publicationId: state.publicationId };
state.products.forEach((product, index) => variables['id' + index] = product.id);
fs.writeFileSync(path.join(directory, 'publish-family-items-variables.json'), JSON.stringify(variables, null, 2));
console.log('Prepared an idempotent Online Store publication operation for exactly 40 sample products.');
